"""Batch-classify timesheet notes against contract scope with the Anthropic API.

Reproduces data/classifications.json from data/project.json using
prompts/classify_entries.md.

Usage:
  pip install anthropic
  export ANTHROPIC_API_KEY=...
  python3 scripts/classify.py            # writes data/classifications.json
  python3 scripts/classify.py --check    # compares a fresh run with the saved file

The saved file in this repo was produced in the build session with the same
prompt. This script is the repeatable path; it was not run in this repo
because no API key was available there.
"""
import argparse
import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MODEL = os.environ.get("SCOPE_GUARD_MODEL", "claude-haiku-5-5")
VALID_LABELS = {"in_scope", "out_of_scope", "unclear"}


def build_prompt(project: dict) -> str:
    template = (ROOT / "prompts" / "classify_entries.md").read_text(encoding="utf-8")
    template = template.split("\n---\n", 1)[1]
    clauses = "\n".join(f'{s["id"]} ({s["type"]}): {s["text"]}' for s in project["scope"])
    entries = [{k: e[k] for k in ("id", "phase", "hours", "note")} for e in project["entries"]]
    return template.replace("{{SCOPE_CLAUSES}}", clauses).replace("{{ENTRIES_JSON}}", json.dumps(entries, indent=1))


def parse(text: str) -> list:
    start, end = text.find("["), text.rfind("]")
    if start < 0 or end < 0:
        raise ValueError("No JSON array in the reply")
    return json.loads(text[start : end + 1])


def validate(results: list, project: dict) -> list:
    """Guardrails: every note answered once, labels valid, clauses real."""
    ids = {e["id"] for e in project["entries"]}
    clause_ids = {s["id"] for s in project["scope"]} | {""}
    problems = []
    seen = set()
    for r in results:
        if r.get("id") not in ids:
            problems.append(f"unknown id {r.get('id')}")
        if r.get("id") in seen:
            problems.append(f"duplicate id {r.get('id')}")
        seen.add(r.get("id"))
        if r.get("label") not in VALID_LABELS:
            problems.append(f"{r.get('id')}: bad label {r.get('label')}")
        if r.get("clause", "") not in clause_ids:
            problems.append(f"{r.get('id')}: unknown clause {r.get('clause')}")
        if r.get("label") == "out_of_scope" and not r.get("driver"):
            problems.append(f"{r.get('id')}: out_of_scope without a driver")
    missing = ids - seen
    if missing:
        problems.append(f"missing ids {sorted(missing)}")
    return problems


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="compare with the saved file instead of overwriting it")
    args = ap.parse_args()

    import anthropic  # imported here so --help works without the package

    project = json.loads((ROOT / "data" / "project.json").read_text(encoding="utf-8"))
    client = anthropic.Anthropic()
    msg = client.messages.create(
        model=MODEL,
        max_tokens=8000,
        messages=[{"role": "user", "content": build_prompt(project)}],
    )
    results = parse("".join(b.text for b in msg.content if b.type == "text"))
    problems = validate(results, project)
    if problems:
        print("Validation failed:\n  " + "\n  ".join(problems))
        sys.exit(1)

    out = ROOT / "data" / "classifications.json"
    if args.check:
        saved = {r["id"]: r["label"] for r in json.loads(out.read_text())["results"]}
        fresh = {r["id"]: r["label"] for r in results}
        diff = {k: (saved[k], fresh.get(k)) for k in saved if saved[k] != fresh.get(k)}
        agree = 1 - len(diff) / len(saved)
        print(f"Label agreement with saved run: {agree:.0%}")
        for k, (a, b) in diff.items():
            print(f"  {k}: saved {a}, fresh {b}")
        return

    out.write_text(json.dumps({"_how": f"Generated by scripts/classify.py with {MODEL}.", "results": results}, indent=2))
    print(f"Wrote {len(results)} results to {out}")


if __name__ == "__main__":
    main()
